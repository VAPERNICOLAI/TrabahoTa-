
import os
import sqlite3
import psycopg

from pathlib import Path
from psycopg.rows import dict_row

DATABASE_PATH = Path(
    os.environ.get(
        "SQLITE_DATABASE_PATH",
        str(Path(__file__).resolve().parent / "trabahota.db")
    )
)
DATABASE_URL = os.environ.get("DATABASE_URL")
USE_POSTGRES = bool(DATABASE_URL)

if os.environ.get("FLASK_ENV") == "production" and not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is required in production")


def get_db_connection():
    if USE_POSTGRES:
        return psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row,
            connect_timeout=10
        )

    connection = sqlite3.connect(DATABASE_PATH)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")

    return connection


def init_db():
    connection = get_db_connection()

    primary_key = (
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if USE_POSTGRES
        else "INTEGER PRIMARY KEY AUTOINCREMENT"
    )

    try:
        # TABLE 1: USERS
        connection.execute(f"""
            CREATE TABLE IF NOT EXISTS users (
                id {primary_key},
                full_name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL CHECK (
                    role IN ('student', 'company', 'admin')
                ),
                is_verified INTEGER NOT NULL DEFAULT 0,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # TABLE 2: COMPANIES
        connection.execute(f"""
            CREATE TABLE IF NOT EXISTS companies (
                id {primary_key},
                user_id INTEGER NOT NULL UNIQUE,
                company_name TEXT NOT NULL,
                description TEXT,
                is_approved INTEGER NOT NULL DEFAULT 0,
                FOREIGN KEY (user_id) REFERENCES users(id)
            )
        """)

        # TABLE 3: OPPORTUNITIES
        connection.execute(f"""
            CREATE TABLE IF NOT EXISTS opportunities (
                id {primary_key},
                company_id INTEGER NOT NULL,
                title TEXT NOT NULL,
                description TEXT NOT NULL,
                opportunity_type TEXT NOT NULL,
                location TEXT,
                deadline DATE,
                status TEXT NOT NULL DEFAULT 'open',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (company_id) REFERENCES companies(id)
            )
        """)

        # TABLE 4: APPLICATIONS
        connection.execute(f"""
            CREATE TABLE IF NOT EXISTS applications (
                id {primary_key},
                student_id INTEGER NOT NULL,
                opportunity_id INTEGER NOT NULL,
                status TEXT NOT NULL DEFAULT 'submitted',
                applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (student_id) REFERENCES users(id),
                FOREIGN KEY (opportunity_id) REFERENCES opportunities(id),
                UNIQUE (student_id, opportunity_id)
            )
        """)

        # TABLE 5: STUDENT PROFILES
        connection.execute("""
            CREATE TABLE IF NOT EXISTS student_profiles (
                user_id INTEGER PRIMARY KEY,
                student_number TEXT UNIQUE,
                college TEXT,
                degree_program TEXT,
                year_level INTEGER CHECK (
                    year_level BETWEEN 1 AND 6
                ),
                contact_number TEXT,
                bio TEXT,
                skills TEXT,
                qualifications TEXT,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (user_id) REFERENCES users(id)
                    ON DELETE CASCADE
            )
        """)

        # TABLE 6: STUDENT RESUMES
        binary_type = "BYTEA" if USE_POSTGRES else "BLOB"

        connection.execute(f"""
            CREATE TABLE IF NOT EXISTS student_resumes (
                user_id INTEGER PRIMARY KEY,
                file_name TEXT NOT NULL,
                mime_type TEXT NOT NULL CHECK (
                    mime_type = 'application/pdf'
                ),
                file_size INTEGER NOT NULL CHECK (
                    file_size BETWEEN 1 AND 2097152
                ),
                file_data {binary_type} NOT NULL CHECK (
                    length(file_data) = file_size
                ),
                uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (user_id) REFERENCES users(id)
                    ON DELETE CASCADE
            )
        """)

        connection.commit()

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()
